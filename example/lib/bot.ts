import { createMemoryState } from "@chat-adapter/state-memory";
import { createRedisState } from "@chat-adapter/state-redis";
import { createWatiAdapter, type WatiAdapter } from "@wati-io/chat-sdk-adapter";
import {
  Actions,
  Button,
  Card,
  CardText,
  Chat,
  Select,
  SelectOption,
  type Message,
  type Thread,
} from "chat";

const HELP = `*Wati × Chat SDK test bot*

Send one of these:
• *help*: this list
• *format*: Markdown → WhatsApp formatting
• *buttons*: reply buttons
• *menu*: a list menu
• *file*: a generated text file (upload)
• *pdf*: a PDF sent by URL
• *typing*: typing indicator, then a reply
• *history*: the last messages in this chat
• *long*: a message over 4,096 characters (gets split)
• *template <name> [var=value]*: send an approved template to you

Send a photo, voice note or document and I'll describe it. React to a message and I'll notice.`;

/** Vercel's Redis integrations set REDIS_URL (Redis Cloud) or KV_URL (Upstash). */
export function redisUrl(): string | undefined {
  return process.env.REDIS_URL || process.env.KV_URL || undefined;
}

let bot: Chat<{ wati: WatiAdapter }> | null = null;

/** Create the bot on first use, so `next build` works before env vars are set. */
export function getBot(): Chat<{ wati: WatiAdapter }> {
  if (bot) return bot;

  bot = new Chat({
    userName: "wati-test-bot",
    adapters: { wati: createWatiAdapter() },
    state: redisUrl() ? createRedisState({ url: redisUrl() }) : createMemoryState(),
    // Customers often send several messages in a row; handle them in order.
    concurrency: "queue",
    logger: process.env.NODE_ENV === "production" ? "info" : "debug",
  });

  bot.onDirectMessage(async (thread, message) => {
    await handleMessage(thread, message);
  });

  bot.onAction(["approve", "reject"], async (event) => {
    const verb = event.actionId === "approve" ? "Approved ✅" : "Rejected ❌";
    await event.thread?.post(`${verb} request *${event.value}* (tapped by ${event.user.userName})`);
  });

  bot.onAction("size", async (event) => {
    await event.thread?.post(`You picked size *${event.value}*.`);
  });

  bot.onReaction(async (event) => {
    await event.thread.post(
      event.added
        ? `You reacted ${event.rawEmoji} to message ${event.messageId.slice(0, 16)}…`
        : "You removed a reaction.",
    );
  });

  return bot;
}

async function handleMessage(thread: Thread, message: Message): Promise<void> {
  if (message.attachments.length > 0) {
    await describeAttachments(thread, message);
    return;
  }

  const text = message.text.trim();
  const [command = "", ...args] = text.split(/\s+/);

  switch (command.toLowerCase()) {
    case "help":
    case "hi":
    case "hello":
      await thread.post(HELP);
      return;

    case "format":
      await thread.post({
        markdown: [
          "**Bold**, _italic_, ~~strikethrough~~ and `inline code`.",
          "",
          "- a bullet",
          "- another bullet",
          "",
          "1. first",
          "2. second",
          "",
          "> a quote",
          "",
          "[A link](https://docs.wati.io)",
          "",
          "| Plan | Price |",
          "| --- | --- |",
          "| Growth | $49 |",
          "| Pro | $99 |",
          "",
          "```",
          "const answer = 42;",
          "```",
        ].join("\n"),
      });
      return;

    case "buttons":
      await thread.post(
        Card({
          title: "Refund request #1042",
          children: [
            CardText("Customer asked for a $25 refund. Approve it?"),
            Actions([
              Button({ id: "approve", label: "Approve", value: "1042" }),
              Button({ id: "reject", label: "Reject", value: "1042" }),
            ]),
          ],
        }),
      );
      return;

    case "menu":
    case "list":
      await thread.post(
        Card({
          title: "T-shirt sizes",
          children: [
            CardText("Which size would you like?"),
            Actions([
              Select({
                id: "size",
                label: "Sizes",
                options: [
                  SelectOption({ label: "Small", value: "S", description: "Chest 86–91 cm" }),
                  SelectOption({ label: "Medium", value: "M", description: "Chest 96–101 cm" }),
                  SelectOption({ label: "Large", value: "L", description: "Chest 106–111 cm" }),
                ],
              }),
            ]),
          ],
        }),
      );
      return;

    case "file":
      await thread.post({
        markdown: "Here is a generated file.",
        files: [
          {
            filename: "hello-from-chat-sdk.txt",
            mimeType: "text/plain",
            data: Buffer.from(
              `Generated by the Wati Chat SDK test bot at ${new Date().toISOString()}\n`,
            ),
          },
        ],
      });
      return;

    case "pdf":
      await thread.post({
        markdown: "A sample PDF, sent by URL.",
        attachments: [
          {
            type: "file",
            name: "dummy.pdf",
            mimeType: "application/pdf",
            url: "https://www.w3.org/WAI/ER/tests/xhtml/testfiles/resources/pdf/dummy.pdf",
          },
        ],
      });
      return;

    case "typing":
      await thread.startTyping();
      await new Promise((resolve) => setTimeout(resolve, 3000));
      await thread.post("Done thinking. Did you see the typing indicator?");
      return;

    case "history": {
      const page = await thread.adapter.fetchMessages(thread.id, { limit: 10 });
      const lines = page.messages.map((m) => {
        const who = m.author.isMe ? "us" : "you";
        const body = m.text ? m.text.slice(0, 40) : `[${m.attachments[0]?.type ?? "no text"}]`;
        return `• ${who}: ${body}`;
      });
      await thread.post(
        lines.length ? `Last ${lines.length} messages, oldest first:\n${lines.join("\n")}` : "No history found.",
      );
      return;
    }

    case "long": {
      const paragraph =
        "This paragraph is repeated to build a message longer than WhatsApp's 4,096-character limit. ";
      await thread.post(Array.from({ length: 60 }, (_, i) => `${i + 1}. ${paragraph}`).join("\n\n"));
      return;
    }

    case "template": {
      const templateName = args[0];
      if (!templateName) {
        await thread.post(
          "Usage: *template <template_name> [variable=value ...]*\nExample: template new_chat_v1 name=Ana\nThe template must be approved in Wati.",
        );
        return;
      }
      // Remaining words like `name=Ana` fill the template's {{variables}}.
      const parameters = args.slice(1).flatMap((arg) => {
        const index = arg.indexOf("=");
        return index > 0 ? [{ name: arg.slice(0, index), value: arg.slice(index + 1) }] : [];
      });
      const wati = getBot().getAdapter("wati");
      const { waId } = wati.decodeThreadId(thread.id);
      try {
        const result = await wati.sendTemplate(thread.id, { templateName, parameters });
        await thread.post(`Template *${templateName}* sent to ${waId} (broadcast ${result.broadcastId ?? "n/a"}).`);
      } catch (error) {
        await thread.post(
          `Wati didn't send template *${templateName}*: ${error instanceof Error ? error.message : String(error)}`,
        );
      }
      return;
    }

    default:
      await thread.post(`You said: ${text || "(nothing)"}\n\nSend *help* to see what I can do.`);
  }
}

async function describeAttachments(thread: Thread, message: Message): Promise<void> {
  const lines: string[] = [];
  for (const attachment of message.attachments) {
    let size = "size unknown";
    try {
      const data = await attachment.fetchData?.();
      if (data) size = `${data.byteLength.toLocaleString()} bytes downloaded`;
    } catch (error) {
      size = `download failed: ${error instanceof Error ? error.message : String(error)}`;
    }
    lines.push(`• ${attachment.type}${attachment.name ? ` "${attachment.name}"` : ""}: ${size}`);
  }
  const caption = message.text ? `\nCaption: ${message.text}` : "";
  await thread.post(`Got ${lines.length} attachment(s):\n${lines.join("\n")}${caption}`);
}
